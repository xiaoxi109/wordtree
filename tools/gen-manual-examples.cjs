#!/usr/bin/env node
/**
 * 把 .cache/ex-batches/batch-me-*.json 里手写的例句汇总成
 * src/data/generated/manual-examples.ts。
 *
 * 与 gen-examples.cjs 的 store 不同：这里不受 collectTargets() 限制，
 * 因此 CEFR 主库词、短语词（in fact / a bit…）也能拿到手写例句。
 * 装配层（data/index.ts）对命中 manual 的词优先采用这里的例句。
 */
'use strict'
const fs = require('node:fs')
const path = require('node:path')
const ROOT = path.resolve(__dirname, '..')
const BATCH_DIR = path.join(ROOT, '.cache', 'ex-batches')
const OUT = path.join(ROOT, 'src', 'data', 'generated', 'manual-examples.ts')

const norm = (s) => String(s || '').toLowerCase().normalize('NFKC').replace(/[^a-z0-9'-]/g, '')

const map = new Map()
for (const file of fs.readdirSync(BATCH_DIR).filter((f) => /^batch-me-.*\.json$/.test(f)).sort()) {
  let data
  try { data = JSON.parse(fs.readFileSync(path.join(BATCH_DIR, file), 'utf8')) } catch { continue }
  const items = Array.isArray(data) ? data : data?.items
  if (!Array.isArray(items)) continue
  for (const it of items) {
    const word = String(it?.word ?? '').trim()
    const list = (Array.isArray(it?.examples) ? it.examples : [])
      .map((e) => ({ en: String(e?.en ?? '').trim(), zh: String(e?.zh ?? '').trim() }))
      .filter((e) => e.en && e.zh)
      .slice(0, 2)
    if (!word || !list.length) continue
    // 后面的批次覆盖前面的（便于修订）
    map.set(norm(word), { word, examples: list })
  }
}

const keys = [...map.keys()].sort()
const body = keys.map((k) => {
  const { examples } = map.get(k)
  const ex = examples.map((e) => `{ en: ${JSON.stringify(e.en)}, zh: ${JSON.stringify(e.zh)} }`).join(', ')
  return `  ${JSON.stringify(k)}: [${ex}],`
}).join('\n')
const content =
  `// AUTO-GENERATED by tools/gen-manual-examples.cjs — 请勿手工编辑。\n` +
  `// 手写例句覆盖 ${keys.length} 个词（含 CEFR 主库词与短语词）。\n` +
  `import type { Example } from '../types'\n\n` +
  `export const MANUAL_EXAMPLES: Record<string, Example[]> = {\n${body}\n}\n`
fs.writeFileSync(OUT, content, 'utf8')
console.log(`✓ 写入 ${keys.length} 词 → ${path.relative(ROOT, OUT)}`)
