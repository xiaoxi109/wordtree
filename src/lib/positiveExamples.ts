/** 这条例句是否属于消极语境 */
export function isNegativeExample(zh: string): boolean {
  if (!zh) return false
  if (STRONG_NEGATIVE_ZH.test(zh)) {
    // 「别害怕」「不要难过」这类劝慰句是正向引导，保留
    return !ENCOURAGING.test(zh)
  }
  if (NEUTRAL_OVERRIDE.test(zh)) return false
  return WEAK_NEGATIVE_ZH.test(zh)
}

/**
 * 过滤消极例句，并把积极例句排到前面。
 * 不修改原数组，也不改动词库源数据。
 */
export function positiveExamples<T extends ExampleLike>(examples: T[] | undefined | null): T[] {
  if (!examples || examples.length === 0) return []
  return examples
    .map((ex, i) => ({ ex, i, score: POSITIVE_ZH.test(ex.zh ?? '') ? 1 : 0 }))
    .filter(({ ex }) => !isNegativeExample(ex.zh ?? ''))
    .sort((a, b) => b.score - a.score || a.i - b.i)
    .map(({ ex }) => ex)
}
