/**
 * 例句展示规范：过滤不适内容 + 积极优先排序。
 *
 * v2 主题感知（解决「常用词一句例句都没有」的问题）
 * ------------------------------------------------------------------
 * 之前所有负向语境一刀切过滤，结果 die / crime / sick / accident 这类
 * **词义本身就是负向**的常用词，例句被全部滤空，学习者反而看不到用法。
 *
 * 现在分三层处理：
 *   1. GRAPHIC_ZH —— 血腥、尸体、露骨、自伤描写：任何情况下都不展示。
 *   2. 主题判定 —— 负向概念按主题分组（death / crime / illness / sad …）。
 *      如果例句命中的负向主题**正是这个单词自己的词义**（单词释义里出现了
 *      该主题的词），说明例句是在讲这个主题本身，属于中性事实陈述 → 放行；
 *      反之（例句讲的是另一个负向主题）→ 过滤。
 *      例：die 的释义含「死亡」→ "他去年去世了" 放行；
 *          happy 的释义不含负向主题 → "我很难过" 过滤。
 *   3. 弱负向字（累/怕/脏/错…）—— 默认过滤，除非整句是积极表达
 *      （NEUTRAL_OVERRIDE）或劝慰句（ENCOURAGING）。
 */
export interface ExampleLike {
  en: string
  zh: string
}

