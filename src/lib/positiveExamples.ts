/* ---------------------------- 主题判定 ---------------------------- */

/** 每个主题预编译成正则，避免运行时重复拼串 */
const TOPIC_RE: { key: string; re: RegExp }[] = Object.entries(TOPIC_TERMS).map(
  ([key, terms]) => ({ key, re: new RegExp(terms.join('|'), 'g') }),
)

/** 文本命中的负向主题集合 */
export function negativeTopicsOf(text: string): Set<string> {
  const out = new Set<string>()
  if (!text) return out
  for (const { key, re } of TOPIC_RE) {
    re.lastIndex = 0
    if (re.test(text)) out.add(key)
  }
  return out
}

/** 单词释义命中的负向主题集合 —— 即「这个单词本身讲的是哪些负向概念」 */
export function topicKeysOfMeaning(meaning: string): Set<string> {
  return negativeTopicsOf(meaning)
}

/**
 * 这条例句是否属于消极语境。
 *
 * 核心原则：**负向词如果属于这个单词自己的词义，就放行**（例句在解释这个词本身），
 * 否则过滤（例句无端引入与单词无关的负面内容）。例如：
 *   - die（释义含「死亡」）→ "竹子开花后就会死亡" 放行；
 *   - happy（释义无负向词）→ "我很难过" 过滤。
 *
 * @param meaning 该词的中文释义（用于判断负向词是否属于本词词义）。缺省时按「无词义白名单」处理。
 */
export function isNegativeExample(zh: string, meaning?: string): boolean {
  if (!zh) return false
  // 1) 血腥露骨：任何情况都过滤
  if (GRAPHIC_ZH.test(zh)) return true
  // 2) 劝慰句是正向引导
  if (ENCOURAGING.test(zh)) return false

  // 3) 收集例句里命中的负向词
  const hits: string[] = []
  for (const { re } of TOPIC_RE) {
    re.lastIndex = 0
    let m: RegExpExecArray | null
    while ((m = re.exec(zh))) hits.push(m[0])
  }
  if (!hits.length) {
    // 无主题命中：走弱负向字兜底，但要排除「弱负向字正是本词释义的一部分」
    if (NEUTRAL_OVERRIDE.test(zh)) return false
    const weak = /累|饿|苦|穷|贫|乱|脏|错|麻烦|危险|怕|怒|愁|忧|慌|惧|厌|嫌|辱|讽|疲|烦|毁|损|吵|祸|怨|疯|凶|恶|毒|伤|疼|痛|惨|缺陷|遗憾|困难|艰难|乏|旱|燥|琐/g
    weak.lastIndex = 0
    let m: RegExpExecArray | null
    while ((m = weak.exec(zh))) {
      // 该弱负向字若出现在单词释义里（如「错觉」的「错」、「讽刺」的「讽」），豁免
      if (meaning && meaning.includes(m[0])) continue
      return true
    }
    return false
  }

  // 4) 词义本身就是负向概念（如 die/crime/sick/terror）→ 例句在解释这个词，放行。
  //    词义完全中性/正向（如 happy/apple）→ 例句出现负向内容属于无端引入，过滤。
  if (!meaning) return true
  return topicKeysOfMeaning(meaning).size === 0
}

/**
 * 过滤消极例句，并把积极例句排到前面。
 * 不修改原数组，也不改动词库源数据。
 *
 * @param opts.meaning 该词的中文释义 —— 用于判断例句的负向主题是否就是本词的词义
 */
export function positiveExamples<T extends ExampleLike>(
  examples: T[] | undefined | null,
  opts?: { meaning?: string },
): T[] {
  if (!examples || examples.length === 0) return []
  return examples
    .map((ex, i) => ({ ex, i, score: POSITIVE_ZH.test(ex.zh ?? '') ? 1 : 0 }))
    .filter(({ ex }) => !isNegativeExample(ex.zh ?? '', opts?.meaning))
    .sort((a, b) => b.score - a.score || a.i - b.i)
    .map(({ ex }) => ex)
}
